CREATE TABLE IF NOT EXISTS market.fii_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker text,
    document_type text NOT NULL,
    natural_key text NOT NULL,
    reference_date date,
    source_published_at timestamptz,
    first_observed_at timestamptz NOT NULL,
    source_url text NOT NULL,
    current_version_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (document_type, natural_key)
);

CREATE TABLE IF NOT EXISTS market.fii_document_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES market.fii_documents(id) ON DELETE CASCADE,
    revision_no integer NOT NULL CHECK (revision_no > 0),
    content_sha256 text NOT NULL,
    storage_backend text NOT NULL CHECK (storage_backend IN ('supabase_storage','local_cache','remote_only')),
    storage_key text,
    mime_type text,
    byte_size bigint,
    page_count integer,
    downloaded_at timestamptz NOT NULL DEFAULT now(),
    supersedes_id bigint REFERENCES market.fii_document_versions(id) ON DELETE SET NULL,
    metadata_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (document_id, revision_no),
    UNIQUE (document_id, content_sha256)
);

