SET collected_at = COALESCE(collected_at, fetched_at)
WHERE collected_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_brapi_raw_request
    ON market.brapi_raw_payloads (endpoint, request_fingerprint, collected_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_brapi_raw_success_content
    ON market.brapi_raw_payloads (endpoint, request_fingerprint, content_sha256)
    WHERE request_status = 'success' AND content_sha256 IS NOT NULL;

CREATE TABLE IF NOT EXISTS market.fii_source_releases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider text NOT NULL,
    endpoint text NOT NULL,
    natural_key text NOT NULL,
    reference_date date,
    source_published_at timestamptz,
    first_observed_at timestamptz NOT NULL,
    knowledge_at timestamptz NOT NULL,
    availability_quality text NOT NULL CHECK (availability_quality IN
        ('verified_publication','first_observed_proxy','retrospective_backfill','migration_baseline')),
    revision_no integer NOT NULL DEFAULT 1 CHECK (revision_no > 0),
    supersedes_id bigint REFERENCES market.fii_source_releases(id) ON DELETE SET NULL,
    raw_payload_id bigint NOT NULL REFERENCES market.brapi_raw_payloads(id) ON DELETE RESTRICT,
    content_sha256 text NOT NULL,
    metadata_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (provider, endpoint, natural_key, revision_no),
    UNIQUE (provider, endpoint, natural_key, content_sha256)
);
CREATE INDEX IF NOT EXISTS idx_fii_source_release_pit
    ON market.fii_source_releases (provider, endpoint, natural_key, knowledge_at DESC);

