CREATE TABLE IF NOT EXISTS market.fii_quality_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_type text NOT NULL DEFAULT 'ingestion',
    status text NOT NULL CHECK (status IN ('running','passed','blocked','failed')),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    summary_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    correlation_id uuid
);

CREATE TABLE IF NOT EXISTS market.fii_quality_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES market.fii_quality_runs(id) ON DELETE CASCADE,
    rule_code text NOT NULL,
    entity_type text NOT NULL,
    entity_key text,
    severity text NOT NULL CHECK (severity IN ('info','low','medium','high','critical')),
    status text NOT NULL CHECK (status IN ('passed','warning','failed','quarantined')),
    observed_value jsonb NOT NULL DEFAULT '{}'::jsonb,
    message text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_fii_quality_results_run
    ON market.fii_quality_results (run_id, severity, status);

CREATE TABLE IF NOT EXISTS market.fii_reconciliation_issues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker text NOT NULL,
    metric_name text NOT NULL,
    reference_date date NOT NULL,
    left_source text NOT NULL,
    left_value jsonb,
    right_source text NOT NULL,
    right_value jsonb,
    absolute_difference numeric,
    relative_difference numeric,
    tolerance numeric,
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','accepted','resolved','rejected')),
    resolution_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    detected_at timestamptz NOT NULL DEFAULT now(),
    resolved_at timestamptz,
    UNIQUE (ticker, metric_name, reference_date, left_source, right_source)
);

