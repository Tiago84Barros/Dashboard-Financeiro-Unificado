CREATE TABLE IF NOT EXISTS market.fii_extraction_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_version_id bigint NOT NULL REFERENCES market.fii_document_versions(id) ON DELETE CASCADE,
    parser_name text NOT NULL,
    parser_version text NOT NULL,
    status text NOT NULL CHECK (status IN ('running','passed','needs_review','failed')),
    text_method text,
    confidence numeric CHECK (confidence BETWEEN 0 AND 1),
    layout_signature text,
    metrics_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    error_message text,
    FOREIGN KEY (parser_name, parser_version)
        REFERENCES market.fii_parser_versions(parser_name, parser_version)
);

CREATE TABLE IF NOT EXISTS market.fii_extraction_evidence (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_run_id bigint NOT NULL REFERENCES market.fii_extraction_runs(id) ON DELETE CASCADE,
    metric_name text NOT NULL,
    raw_value text,
    normalized_value jsonb,
    unit text,
    page_number integer,
    bbox_json jsonb,
    evidence_text text NOT NULL,
    confidence numeric NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    validation_status text NOT NULL DEFAULT 'pending'
        CHECK (validation_status IN ('pending','accepted','corrected','rejected')),
    reviewer_id text,
    reviewed_at timestamptz,
    review_note text
);

