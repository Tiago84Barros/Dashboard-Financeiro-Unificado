-- de CRIs e fila concorrente para documentos publicos.
-- O schema market permanece backend-only e fechado para a Data API.

ALTER TABLE market.historical_prices
    ADD COLUMN IF NOT EXISTS source text,
    ADD COLUMN IF NOT EXISTS raw_payload_id bigint
        REFERENCES market.brapi_raw_payloads(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS knowledge_at timestamptz,
    ADD COLUMN IF NOT EXISTS availability_quality text,
    ADD COLUMN IF NOT EXISTS content_hash text;

UPDATE market.historical_prices
SET source = COALESCE(source, 'brapi_legacy_quote'),
    knowledge_at = COALESCE(knowledge_at, updated_at, now()),
    availability_quality = COALESCE(availability_quality, 'retrospective_backfill')
WHERE source IS NULL OR knowledge_at IS NULL OR availability_quality IS NULL;

