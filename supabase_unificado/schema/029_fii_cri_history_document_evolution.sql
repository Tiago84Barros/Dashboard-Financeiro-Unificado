-- A tabela historica legada continua como estado corrente para compatibilidade.
-- Esta tabela append-only preserva cada revisao observada e e a fonte correta
-- para reconstrucoes point-in-time.
CREATE TABLE IF NOT EXISTS market.historical_price_observations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker text NOT NULL REFERENCES market.assets(ticker) ON DELETE CASCADE,
    date date NOT NULL,
    open numeric(18,6),
    high numeric(18,6),
    low numeric(18,6),
    close numeric(18,6) NOT NULL CHECK (close > 0),
    adjusted_close numeric(18,6),
    volume bigint,
    source text NOT NULL,
    raw_payload_id bigint REFERENCES market.brapi_raw_payloads(id) ON DELETE SET NULL,
    available_at timestamptz NOT NULL,
    knowledge_at timestamptz NOT NULL,
    availability_quality text NOT NULL CHECK (availability_quality IN
        ('verified_publication','first_observed_proxy','retrospective_backfill','migration_baseline')),
    content_hash text NOT NULL,
    observed_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (ticker, date, source, content_hash)
);

INSERT INTO market.historical_price_observations (
    ticker,date,open,high,low,close,adjusted_close,volume,source,
    raw_payload_id,available_at,knowledge_at,availability_quality,content_hash
)
SELECT ticker,date,open,high,low,close,adjusted_close,volume,source,
       raw_payload_id,knowledge_at,knowledge_at,availability_quality,
       COALESCE(content_hash,
                md5(concat_ws('|',ticker,date,open,high,low,close,
                              adjusted_close,volume,source)))
FROM market.historical_prices
WHERE close > 0
ON CONFLICT DO NOTHING;

