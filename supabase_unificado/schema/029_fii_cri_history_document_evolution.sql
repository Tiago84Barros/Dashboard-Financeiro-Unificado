    DROP CONSTRAINT IF EXISTS fii_documents_processing_status_check;
ALTER TABLE market.fii_documents
    ADD CONSTRAINT fii_documents_processing_status_check
    CHECK (processing_status IN
        ('pending','processing','completed','needs_review','failed'));

WITH latest_success AS (
    SELECT DISTINCT ON (dv.document_id)
           dv.document_id, er.status
    FROM market.fii_document_versions dv
    JOIN market.fii_extraction_runs er ON er.document_version_id = dv.id
    WHERE er.status IN ('passed','needs_review')
    ORDER BY dv.document_id, er.finished_at DESC NULLS LAST, er.id DESC
)
UPDATE market.fii_documents d
SET processing_status = CASE
        WHEN r.status = 'needs_review' THEN 'needs_review'
        ELSE 'completed'
    END,
    processing_started_at = NULL,
    processing_worker = NULL,
    last_error = NULL
FROM latest_success r
WHERE r.document_id = d.id;

CREATE INDEX IF NOT EXISTS idx_fii_documents_processing_queue
    ON market.fii_documents
       (processing_status, next_retry_at, reference_date DESC, id DESC)
    WHERE processing_status IN ('pending','failed','processing');

