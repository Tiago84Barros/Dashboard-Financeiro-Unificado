CREATE OR REPLACE FUNCTION market.normalize_fii_entity_name(value text)
RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE
SET search_path = ''
AS $$
  SELECT trim(regexp_replace(
    translate(lower(coalesce(value,'')),
      'áàâãäéèêëíìîïóòôõöúùûüç',
      'aaaaaeeeeiiiiooooouuuuc'),
    '[^a-z0-9]+', ' ', 'g'));
$$;
REVOKE ALL ON FUNCTION market.normalize_fii_entity_name(text) FROM PUBLIC, anon, authenticated;

