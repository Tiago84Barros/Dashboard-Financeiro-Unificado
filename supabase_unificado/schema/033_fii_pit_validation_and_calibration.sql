CREATE TABLE IF NOT EXISTS market.fii_parser_calibrations (
    parser_name text NOT NULL,
    parser_version text NOT NULL,
    metric_name text NOT NULL,
    reviewed_count integer NOT NULL CHECK (reviewed_count >= 0),
    accepted_count integer NOT NULL CHECK (accepted_count >= 0),
    corrected_count integer NOT NULL CHECK (corrected_count >= 0),
    rejected_count integer NOT NULL CHECK (rejected_count >= 0),
    posterior_mean numeric NOT NULL CHECK (posterior_mean BETWEEN 0 AND 1),
    lower_bound numeric NOT NULL CHECK (lower_bound BETWEEN 0 AND 1),
    upper_bound numeric NOT NULL CHECK (upper_bound BETWEEN 0 AND 1),
    calibrated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (parser_name, parser_version, metric_name),
    CHECK (lower_bound <= posterior_mean AND posterior_mean <= upper_bound),
    CHECK (reviewed_count = accepted_count + corrected_count + rejected_count)
);

