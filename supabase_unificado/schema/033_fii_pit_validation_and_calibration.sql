CREATE TABLE IF NOT EXISTS market.fii_registry_observations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj text NOT NULL,
    cvm_code text,
    fund_registry_id text,
    class_registry_id text,
    ticker text,
    legal_name text,
    fund_type text,
    classification text,
    status text NOT NULL,
    registration_date date,
    constitution_date date,
    start_date date,
    cancellation_date date,
    manager_identifier text,
    manager_name text,
    administrator_identifier text,
    administrator_name text,
    reference_date date NOT NULL,
    collected_at timestamptz NOT NULL,
    source text NOT NULL,
    raw_payload_id bigint REFERENCES market.brapi_raw_payloads(id) ON DELETE SET NULL,
    content_hash text NOT NULL,
    raw_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
