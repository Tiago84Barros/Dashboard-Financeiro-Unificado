CREATE TABLE IF NOT EXISTS market.fii_backtest_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_run_id bigint REFERENCES market.fii_validation_runs(id) ON DELETE SET NULL,
    methodology_version text NOT NULL REFERENCES market.fii_methodology_versions(methodology_version),
    formula_version text NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    rebalance_frequency text NOT NULL,
    benchmark_name text NOT NULL,
    top_n integer NOT NULL CHECK (top_n > 0),
    transaction_cost numeric NOT NULL CHECK (transaction_cost >= 0),
    slippage numeric NOT NULL CHECK (slippage >= 0),
    status text NOT NULL CHECK (status IN ('running','passed','blocked','failed')),
    metrics_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    blockers_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_fii_backtest_latest
    ON market.fii_backtest_runs (methodology_version, finished_at DESC);
CREATE INDEX IF NOT EXISTS idx_fii_backtest_validation
    ON market.fii_backtest_runs (validation_run_id) WHERE validation_run_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS market.fii_backtest_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_run_id bigint NOT NULL REFERENCES market.fii_backtest_runs(id) ON DELETE CASCADE,
    decision_date date NOT NULL,
    execution_date date NOT NULL,
    portfolio_return numeric,
    benchmark_return numeric,
    coverage numeric CHECK (coverage BETWEEN 0 AND 1),
    turnover numeric CHECK (turnover >= 0),
    holdings_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (backtest_run_id, decision_date)
);

CREATE TABLE IF NOT EXISTS market.fii_backtest_positions (
    backtest_run_id bigint NOT NULL REFERENCES market.fii_backtest_runs(id) ON DELETE CASCADE,
    decision_date date NOT NULL,
    ticker text NOT NULL,
    weight numeric NOT NULL CHECK (weight > 0 AND weight <= 1),
    PRIMARY KEY (backtest_run_id, decision_date, ticker)
);

